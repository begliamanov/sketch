"""The Claude Code installer puts the tools where the docs say they are, and they run."""

import os
import subprocess
import tempfile
import unittest
from pathlib import Path
from typing import Dict, List, Optional

ROOT = Path(__file__).resolve().parents[2]
INSTALL = ROOT / "adapters" / "claude-code" / "install.sh"
STATE_FIXTURE = Path(__file__).parent / "fixtures" / "state_valid.md"
MARKER = "generated by sketch adapters/claude-code/install.sh"


class InstallCase(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.home = Path(self._tmp.name) / "claude"
        self.work = Path(self._tmp.name) / "work"
        self.work.mkdir()
        self.bin = self.home / "sketch" / "tools" / "bin"

    def install(self, *args: str) -> "subprocess.CompletedProcess[str]":
        env = dict(os.environ, CLAUDE_HOME=str(self.home))
        return subprocess.run(
            ["bash", str(INSTALL), *args], env=env, capture_output=True, text=True, timeout=120
        )

    def launch(
        self, name: str, *args: str, cwd: Optional[Path] = None
    ) -> "subprocess.CompletedProcess[str]":
        return subprocess.run(
            [str(self.bin / name), *args], cwd=str(cwd or self.work),
            capture_output=True, text=True, timeout=60,
        )


class InstallTest(InstallCase):
    def test_installs_cleanly(self) -> None:
        result = self.install()
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_a_launcher_exists_and_is_executable_for_each_tool(self) -> None:
        self.install()
        for name in ("sketch-journal", "sketch-state", "sketch-repo-check", "sketch-plan",
                     "sketch-guard", "sketch-pr"):
            with self.subTest(launcher=name):
                path = self.bin / name
                self.assertTrue(path.is_file())
                self.assertTrue(os.access(str(path), os.X_OK))

    def test_the_journal_launcher_works(self) -> None:
        self.install()
        journal = self.work / "journal.md"
        result = self.launch("sketch-journal", "add", "NOTE", "S1", "-", "hi", "--me",
                             "--journal", str(journal))
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("NOTE    [me] hi", journal.read_text())

    def test_the_state_launcher_works(self) -> None:
        self.install()
        state = self.work / "state.md"
        state.write_text(STATE_FIXTURE.read_text())
        result = self.launch("sketch-state", "check", "--state", str(state))
        self.assertEqual((result.returncode, result.stdout), (0, "ok\n"))

    def test_the_repo_check_launcher_reads_stdin(self) -> None:
        self.install()
        result = subprocess.run(
            [str(self.bin / "sketch-repo-check"), "commit-prefix"], input="fix typo\n",
            cwd=str(self.work), capture_output=True, text=True, timeout=60,
        )
        self.assertEqual(result.returncode, 1)
        self.assertIn("no task prefix", result.stdout)

    def test_a_launcher_ignores_python_files_in_the_current_folder(self) -> None:
        self.install()
        (self.work / "argparse.py").write_text("raise RuntimeError('planted')\n")
        (self.work / "sketch_tools").mkdir()
        (self.work / "sketch_tools" / "__init__.py").write_text("raise RuntimeError('planted')\n")
        result = self.launch("sketch-journal", "--help")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertNotIn("planted", result.stdout + result.stderr)

    def test_exit_codes_pass_through_the_launcher(self) -> None:
        self.install()
        result = self.launch("sketch-journal", "add", "BOGUS", "S1", "-", "x",
                             "--journal", str(self.work / "j.md"))
        self.assertEqual(result.returncode, 3)

    def test_no_placeholder_is_left_in_anything_installed(self) -> None:
        self.install()
        for path in (self.home / "sketch" / "core").rglob("*.md"):
            self.assertNotIn("{{", path.read_text(), str(path))
        for path in list((self.home / "agents").glob("*.md")) + list((self.home / "skills").rglob("SKILL.md")):
            self.assertNotIn("{{", path.read_text(), str(path))

    def test_the_tools_placeholder_points_at_the_launchers(self) -> None:
        self.install()
        text = (self.home / "sketch" / "core" / "orchestrator.md").read_text()
        self.assertIn(str(self.bin) + "/sketch-state", text)

    def test_the_drift_notetaker_agent_is_not_installed(self) -> None:
        self.install()
        self.assertFalse((self.home / "agents" / "drift-notetaker.md").exists())
        self.assertFalse((self.home / "sketch" / "core" / "agents" / "drift-notetaker.md").exists())

    def test_the_installed_tools_have_no_tests_or_caches(self) -> None:
        self.install()
        self.launch("sketch-journal", "--help")  # runs once, may write caches
        package = self.home / "sketch" / "tools" / "sketch_tools"
        self.assertTrue((package / "core" / "cli.py").is_file())
        self.assertFalse((self.home / "sketch" / "tools" / "tests").exists())
        self.assertEqual(list(package.rglob("__pycache__")), [])

    def test_installing_twice_works(self) -> None:
        self.assertEqual(self.install().returncode, 0)
        self.assertEqual(self.install().returncode, 0)

    def test_an_old_generated_agent_is_removed_and_a_user_file_is_not(self) -> None:
        (self.home / "agents").mkdir(parents=True)
        old = self.home / "agents" / "old-agent.md"
        old.write_text("---\nname: old-agent\n---\n<!-- " + MARKER + " (sketch 0.0.1). -->\n")
        mine = self.home / "agents" / "mine.md"
        mine.write_text("my own agent\n")
        self.assertEqual(self.install().returncode, 0)
        self.assertFalse(old.exists())
        self.assertEqual(mine.read_text(), "my own agent\n")

    def test_a_launcher_it_did_not_write_is_never_overwritten(self) -> None:
        self.bin.mkdir(parents=True)
        theirs = self.bin / "sketch-state"
        theirs.write_text("#!/bin/sh\necho mine\n")
        result = self.install()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("sketch-state", result.stderr)
        self.assertEqual(theirs.read_text(), "#!/bin/sh\necho mine\n")


class SettingsSnippetTest(unittest.TestCase):
    """The permission snippet wires the guard in as a hook and allows the launchers."""

    def setUp(self) -> None:
        import json

        self.snippet = json.loads((ROOT / "adapters" / "claude-code" / "settings.snippet.json").read_text())

    def test_the_guard_runs_before_every_bash_command(self) -> None:
        hooks = self.snippet["hooks"]["PreToolUse"]
        bash = [h for h in hooks if h["matcher"] == "Bash"]
        self.assertEqual(len(bash), 1)
        commands = [h["command"] for h in bash[0]["hooks"]]
        self.assertEqual(len(commands), 1)
        self.assertIn("sketch/tools/bin/sketch-guard check-command", commands[0])
        self.assertIn("--protect main", commands[0])
        self.assertIn("--protect master", commands[0])
        self.assertIn("--state .sketch/state.md", commands[0])
        self.assertEqual(bash[0]["hooks"][0]["type"], "command")

    def test_the_launchers_are_allowed(self) -> None:
        self.assertIn("Bash(~/.claude/sketch/tools/bin/*)", self.snippet["permissions"]["allow"])

    def test_the_deny_list_is_still_there(self) -> None:
        deny = self.snippet["permissions"]["deny"]
        self.assertIn("Bash(gh pr merge:*)", deny)
        self.assertIn("Bash(git push --force:*)", deny)


class UninstallTest(InstallCase):
    def test_removes_what_it_wrote_and_nothing_else(self) -> None:
        self.install()
        mine = self.home / "agents" / "mine.md"
        mine.write_text("my own agent\n")
        result = self.install("uninstall")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertFalse(self.bin.exists())
        self.assertFalse((self.home / "sketch").exists())
        self.assertEqual(list((self.home / "skills").glob("*")) if (self.home / "skills").exists() else [], [])
        self.assertEqual([p.name for p in (self.home / "agents").glob("*.md")], ["mine.md"])


if __name__ == "__main__":
    unittest.main()
